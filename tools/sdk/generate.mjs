#!/usr/bin/env node
// Generates the SDKs and the CLI command table from generated/openapi.json and
// registry/operations.yaml, with open-source generators only:
//
//   TypeScript  openapi-typescript (types)          -> sdk/typescript/src/schema.ts
//   Python      openapi-python-client (models, IO)  -> sdk/python/src/kofra/_generated/
//   Go          oapi-codegen (models, client)       -> sdk/go/kofra/api/gen.go
//
// plus, from the registry, the thin per-operation layer of each SDK
// (client.<resource>.<method>()) and the CLI's command table. The hand-written
// cores (auth, retries, idempotency keys, errors, pagination) are not touched.
// CI runs this and fails on any difference from the committed files.
//
// Needs: node, uv (Python generator), go (Go generator, pinned as a go.mod tool).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import openapiTS, { astToString } from 'openapi-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const spec = JSON.parse(readFileSync(join(root, 'generated/openapi.json'), 'utf8'));
const registry = YAML.parse(
	readFileSync(join(root, 'registry/operations.yaml'), 'utf8')
).operations;
const PY_GENERATOR = 'openapi-python-client==0.30.0';
const HEADER = 'Generated by tools/sdk/generate.mjs from generated/openapi.json. Do not edit.';

const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^[a-z]/, (c) => c.toUpperCase());
const snake = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '_');
const resolve = (o) =>
	o?.$ref
		? o.$ref
				.split('/')
				.slice(1)
				.reduce((x, k) => x[k], spec)
		: o;

/** Every operation with what the generators need to know about it. */
function operations() {
	const ops = [];
	for (const [path, item] of Object.entries(spec.paths)) {
		for (const method of ['get', 'post', 'patch', 'delete']) {
			const op = item[method];
			if (!op) continue;
			const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map((p) => ({
				raw: p,
				...resolve(p)
			}));
			const [resource, name] = op.operationId.split('.');
			const row = registry.find((r) => r.operation_id === op.operationId);
			if (!row) throw new Error(`no registry row for ${op.operationId}`);
			ops.push({
				id: op.operationId,
				resource,
				name,
				method: method.toUpperCase(),
				path,
				tag: op.tags[0],
				summary: op.summary,
				success: op['x-kofra-success'],
				dryRun: Boolean(op['x-kofra-dry-run']),
				paginated: Boolean(op['x-kofra-paginated']),
				pathParams: params.filter((p) => p.in === 'path'),
				queryParams: params.filter((p) => p.in === 'query'),
				headerParams: params.filter((p) => p.in === 'header'),
				body: Boolean(op.requestBody),
				destructive: method === 'delete',
				cli: row.cli
			});
		}
	}
	return ops;
}

const resources = (ops) => [...new Set(ops.map((o) => o.resource))];

// ---------------------------------------------------------------- TypeScript

async function typescript(ops) {
	const ast = await openapiTS(spec);
	writeFileSync(join(root, 'sdk/typescript/src/schema.ts'), `// ${HEADER}\n\n${astToString(ast)}`);

	const lines = [
		`// ${HEADER}`,
		`import type { components, operations } from './schema.ts';`,
		`import type { CallOptions, Core } from './core.ts';`,
		'',
		`type Json<R> = R extends { content: { 'application/json': infer T } } ? T : never;`,
		`/** The plan returned by \`dry_run: true\`. */`,
		`export type Plan = components['schemas']['Plan'];`,
		''
	];
	for (const r of resources(ops)) {
		lines.push(
			`export class ${pascal(r)}Api {`,
			`\tprivate readonly core: Core;`,
			`\tconstructor(core: Core) {`,
			`\t\tthis.core = core;`,
			`\t}`,
			''
		);
		for (const o of ops.filter((x) => x.resource === r)) {
			const opRef = `operations['${o.id}']`;
			const fields = [];
			if (o.pathParams.length) fields.push(`${opRef}['parameters']['path']`);
			if (o.queryParams.length) fields.push(`NonNullable<${opRef}['parameters']['query']>`);
			if (o.body) fields.push(`{ body: ${opRef}['requestBody']['content']['application/json'] }`);
			const required = o.pathParams.length > 0 || o.body;
			const argsType = fields.length ? fields.join(' & ') : 'Record<string, never>';
			let result = o.success === 204 ? 'undefined' : `Json<${opRef}['responses'][${o.success}]>`;
			if (o.dryRun && o.success !== 200) result = `${result} | Plan`;
			const call = [
				`'${o.method}'`,
				`'${o.path}'`,
				`args`,
				JSON.stringify(o.pathParams.map((p) => p.name)),
				JSON.stringify(o.queryParams.map((p) => p.name)),
				`options`
			].join(', ');
			lines.push(
				`\t/** ${o.summary}. \`${o.id}\`${o.destructive ? '; pass `dry_run: true` to preview' : ''}. */`,
				`\t${camel(o.name)}(args: ${argsType}${required ? '' : ' = {}'}, options?: CallOptions): Promise<${result}> {`,
				`\t\treturn this.core.call(${call}) as Promise<${result}>;`,
				`\t}`,
				''
			);
		}
		lines[lines.length - 1] = '}';
		lines.push('');
	}
	lines.push(
		`/** The resources of the API, as \`client.<resource>\`. */`,
		`export function resources(core: Core) {`,
		`\treturn {`,
		...resources(ops).map((r) => `\t\t${r}: new ${pascal(r)}Api(core),`),
		`\t};`,
		`}`,
		''
	);
	writeFileSync(join(root, 'sdk/typescript/src/operations.ts'), lines.join('\n'));
}

// -------------------------------------------------------------------- Python

function python(ops) {
	const out = join(root, 'sdk/python/src/kofra/_generated');
	rmSync(out, { recursive: true, force: true });
	execFileSync(
		'uvx',
		[
			'--from',
			PY_GENERATOR,
			'openapi-python-client',
			'generate',
			'--meta',
			'none',
			'--path',
			join(root, 'generated/openapi.json'),
			'--output-path',
			out,
			'--config',
			join(root, 'sdk/python/generator.yaml')
		],
		{ stdio: ['ignore', 'ignore', 'inherit'] }
	);
	rmSync(join(out, '.ruff_cache'), { recursive: true, force: true });

	const lines = [
		`# ${HEADER}`,
		'"""Thin per-operation layer: client.<resource>.<method>()."""',
		'',
		'from __future__ import annotations',
		'',
		'from typing import Any',
		''
	];
	for (const o of ops)
		lines.push(`from ._generated.api.${snake(o.tag)} import ${snake(o.id)} as _${snake(o.id)}`);
	lines.push('from ._core import Core', '', '');
	for (const r of resources(ops)) {
		lines.push(
			`class ${pascal(r)}Api:`,
			`    """\`${r}\` operations."""`,
			'',
			`    def __init__(self, core: Core) -> None:`,
			`        self._core = core`,
			''
		);
		for (const o of ops.filter((x) => x.resource === r)) {
			const args = o.pathParams.map((p) => `${snake(p.name)}: str`);
			const pass = o.pathParams.map((p) => snake(p.name));
			if (o.body) {
				args.push('body: Any');
				pass.push('body=body');
			}
			lines.push(
				`    def ${snake(o.name)}(self${args.length ? ', ' + args.join(', ') : ''}, **kwargs: Any) -> Any:`,
				`        """${o.summary}. \`${o.id}\`${o.destructive ? '; pass dry_run=True to preview' : ''}."""`,
				`        return self._core.call(_${snake(o.id)}${pass.length ? ', ' + pass.join(', ') : ''}, **kwargs)`,
				''
			);
		}
		lines.push('');
	}
	lines.push(
		'RESOURCES = {',
		...resources(ops).map((r) => `    "${r}": ${pascal(r)}Api,`),
		'}',
		''
	);
	writeFileSync(
		join(root, 'sdk/python/src/kofra/_operations.py'),
		lines.join('\n').replace(/\n\n\n\nRESOURCES/, '\n\nRESOURCES')
	);
}

// ------------------------------------------------------------------------ Go

function goType(p) {
	const ref = p.schema?.$ref;
	return ref ? `api.${ref.split('/').pop()}` : 'string';
}

function go(ops) {
	rmSync(join(root, 'sdk/go/kofra/gen.go'), { force: true });
	mkdirSync(join(root, 'sdk/go/kofra/api'), { recursive: true });
	execFileSync(
		'go',
		['tool', 'oapi-codegen', '-config', 'oapi-codegen.yaml', '../../generated/openapi.yaml'],
		{
			cwd: join(root, 'sdk/go'),
			stdio: ['ignore', 'ignore', 'inherit']
		}
	);

	const svc = [
		`// Code generated by tools/sdk/generate.mjs from generated/openapi.json. DO NOT EDIT.`,
		'',
		'package kofra',
		'',
		'import (',
		'\t"context"',
		'',
		'\t"github.com/TogetherWeOwn/kofra-api/sdk/go/kofra/api"',
		')',
		''
	];
	for (const r of resources(ops)) {
		svc.push(
			`// ${pascal(r)}Service holds the \`${r}\` operations.`,
			`type ${pascal(r)}Service struct{ c *Client }`,
			''
		);
		for (const o of ops.filter((x) => x.resource === r)) {
			const opName = pascal(o.id.replace('.', '_'));
			const params = [
				'ctx context.Context',
				...o.pathParams.map((p) => `${camel(p.name)} ${goType(p)}`)
			];
			const args = ['ctx', ...o.pathParams.map((p) => camel(p.name))];
			if (o.queryParams.length || o.headerParams.length) {
				params.push(`params *api.${opName}Params`);
				args.push('params');
			}
			if (o.body) {
				params.push(`body api.${opName}JSONRequestBody`);
				args.push('body');
			}
			svc.push(
				`// ${pascal(o.name)}: ${o.summary}. Operation \`${o.id}\`.${o.destructive ? ' Set DryRun in params to preview.' : ''}`,
				`func (s *${pascal(r)}Service) ${pascal(o.name)}(${params.join(', ')}) (*api.${opName}Response, error) {`,
				`\tresp, err := s.c.raw.${opName}WithResponse(${args.join(', ')})`,
				`\tif err != nil {`,
				`\t\treturn nil, err`,
				`\t}`,
				`\treturn resp, checkResponse(resp.HTTPResponse, resp.Body)`,
				`}`,
				''
			);
		}
	}
	svc.push(
		'func (c *Client) initServices() {',
		...resources(ops).map((r) => `\tc.${pascal(r)} = &${pascal(r)}Service{c: c}`),
		'}',
		''
	);
	svc.push(
		'// services are the resources of the API, as client.<Resource>.',
		'type services struct {',
		...resources(ops).map((r) => `\t${pascal(r)} *${pascal(r)}Service`),
		'}',
		''
	);
	writeFileSync(join(root, 'sdk/go/kofra/services_gen.go'), svc.join('\n'));

	const cmd = [
		`// Code generated by tools/sdk/generate.mjs from generated/openapi.json. DO NOT EDIT.`,
		'',
		'package main',
		'',
		'// commands is one entry per API operation, named as in registry/operations.yaml.',
		'var commands = []command{'
	];
	for (const o of ops) {
		const words = o.cli.split(' ');
		const fields = {
			resource: JSON.stringify(words[1]),
			name: JSON.stringify(words[2]),
			operation: JSON.stringify(o.id),
			summary: JSON.stringify(o.summary),
			method: JSON.stringify(o.method),
			path: JSON.stringify(o.path),
			args: `[]string{${o.pathParams.map((p) => JSON.stringify(p.name)).join(', ')}}`,
			query: `[]string{${o.queryParams
				.filter((p) => p.name !== 'dry_run')
				.map((p) => JSON.stringify(p.name))
				.join(', ')}}`,
			body: o.body,
			dryRun: o.dryRun,
			destructive: o.destructive
		};
		cmd.push(
			`\t{${Object.entries(fields)
				.map(([k, v]) => `${k}: ${v}`)
				.join(', ')}},`
		);
	}
	cmd.push('}', '');
	writeFileSync(join(root, 'sdk/go/cmd/kofra/commands_gen.go'), cmd.join('\n'));
	execFileSync('gofmt', ['-w', 'kofra/services_gen.go', 'cmd/kofra/commands_gen.go'], {
		cwd: join(root, 'sdk/go')
	});
}

const ops = operations();
mkdirSync(join(root, 'sdk/typescript/src'), { recursive: true });
await typescript(ops);
python(ops);
go(ops);
console.log(`generated SDKs and CLI table for ${ops.length} operations`);
